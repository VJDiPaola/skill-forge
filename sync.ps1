Write-Host "Library: $LibraryDir" -ForegroundColor DarkGray

switch ($Command) {
    "push" {
        if ($Target -eq "all" -or $Target -eq "codex")   { Push-Codex }
        if ($Target -eq "all" -or $Target -eq "claude")   { Push-Claude }
        if ($Target -eq "all" -or $Target -eq "factory")  { Push-Factory }
        if ($Target -eq "all" -or $Target -eq "desktop")  { Push-Desktop }
        Update-CatalogJson
        Write-Host "`nPush complete." -ForegroundColor Green
    }
    "pull" {
        if ($Target -eq "all" -or $Target -eq "codex")   { Pull-Codex }
        if ($Target -eq "all" -or $Target -eq "claude")   { Pull-Claude }
        if ($Target -eq "all" -or $Target -eq "factory")  { Pull-Factory }
        Update-CatalogJson
        Write-Host "`nPull complete." -ForegroundColor Green
    }
    "status" {
        Show-Status
    }
    "diff" {
        if ($Target -eq "all" -or $Target -eq "codex")   { Diff-Codex }
        if ($Target -eq "all" -or $Target -eq "claude")   { Diff-Claude }
        if ($Target -eq "all" -or $Target -eq "factory")  { Diff-Factory }
        if ($Target -eq "all" -or $Target -eq "desktop")  { Diff-Desktop }
    }
    "search" {
        Search-Skills $Target
    }
    "lint" {
        $lintErrors = Invoke-Lint
        if ($lintErrors -gt 0) { exit 2 }
    }
}
