# --- Search ---

function Search-Skills {
    param([string]$Query)
    if (-not $Query) {
        Write-Host "Usage: .\sync.ps1 search <query>" -ForegroundColor Yellow
        return
    }
    $pattern = [regex]::Escape($Query)
    $found = 0
    foreach ($dir in (Get-ChildItem $LibraryDir -Directory | Sort-Object Name)) {
        $catalogYaml = Join-Path $dir.FullName "catalog.yaml"
        $skillMd = Join-Path $dir.FullName "SKILL.md"
        if (-not (Test-Path $skillMd)) { continue }

        $catalog = Read-CatalogYaml $catalogYaml
        $name = $dir.Name
        $tags = if ($catalog["tags"]) { $catalog["tags"] -join ", " } else { "" }
        $scope = if ($catalog["scope"]) { $catalog["scope"] } else { "" }
        $targets = $catalog["targets"]
        $targetList = @()
        if ($targets) {
            if ($targets["codex"]) { $targetList += "codex" }
            if ($targets["claude"]) { $targetList += "claude" }
            if ($targets["factory"]) { $targetList += "factory" }
        }

        # Extract description
        $content = Get-Content $skillMd -Raw
        $description = ""
        if ($content -match '(?ms)^---\s*\n(.*?)\n---') {
            $fm = $Matches[1]
            $fmLines = $fm -split "`n"
            for ($i = 0; $i -lt $fmLines.Count; $i++) {
                if ($fmLines[$i] -match '^description:\s*(.*)$') {
                    $val = $Matches[1].Trim()
                    if ($val -match '^[>|]-?\s*$') {
                        $parts = @()
                        for ($j = $i + 1; $j -lt $fmLines.Count; $j++) {
                            if ($fmLines[$j] -match '^\s+(.+)') { $parts += $Matches[1].Trim() } else { break }
                        }
                        $description = ($parts -join ' ').Trim()
                    } elseif ($val -match '^"(.+)"$') { $description = $Matches[1] }
                    else { $description = $val.Trim('"') }
                    break
                }
            }
        }

        $searchable = "$name $description $tags"
        if ($searchable -match $pattern) {
            $targetStr = $targetList -join ", "
            Write-Host "  $name" -ForegroundColor Green -NoNewline
            Write-Host " [$targetStr]" -ForegroundColor DarkGray
            if ($description.Length -gt 100) { $description = $description.Substring(0, 100) + "..." }
            Write-Host "    $description" -ForegroundColor Gray
            if ($tags) { Write-Host "    tags: $tags" -ForegroundColor DarkCyan }
            if ($scope -eq "project") { Write-Host "    scope: project" -ForegroundColor DarkYellow }
            $found++
        }
    }
    Write-Host "`n$found skill(s) matched '$Query'" -ForegroundColor Cyan
}

# --- Lint ---

function Invoke-Lint {
    Write-Host "`n=== Skill Library Lint ===" -ForegroundColor Cyan

    # --- Pass 1: discover all skills and their catalog.yaml metadata.
    # Needed upfront so related_exists / related_bidirectional can cross-reference.
    $allSkills = @{}
    foreach ($dir in (Get-ChildItem $LibraryDir -Directory | Sort-Object Name)) {
        $catalogYaml = Join-Path $dir.FullName "catalog.yaml"
        $skillMd = Join-Path $dir.FullName "SKILL.md"
        if (-not (Test-Path $skillMd)) { continue }
        if (-not (Test-Path $catalogYaml)) { continue }
        $allSkills[$dir.Name] = Read-CatalogYaml $catalogYaml
    }

    $errorCount = 0
    $warnCount = 0
    $infoCount = 0

    # Severity constants and display config
    $SevError = "error"
    $SevWarn  = "warning"
    $SevInfo  = "info"
    $sevColors = @{ $SevError = "Red"; $SevWarn = "DarkYellow"; $SevInfo = "DarkGray" }
    $sevLabels = @{ $SevError = "[ERROR]"; $SevWarn = "[WARN] "; $SevInfo = "[INFO] " }

    foreach ($dir in (Get-ChildItem $LibraryDir -Directory | Sort-Object Name)) {
        $catalogYaml = Join-Path $dir.FullName "catalog.yaml"
        $skillMd = Join-Path $dir.FullName "SKILL.md"
        if (-not (Test-Path $skillMd)) { continue }

        $catalog = Read-CatalogYaml $catalogYaml
        $name = $dir.Name
        $skillIssues = @()

        # catalog.yaml exists (error)
        if (-not (Test-Path $catalogYaml)) {
            $skillIssues += @{ Severity = $SevError; Message = "missing catalog.yaml" }
        }

        # id_matches_dir (error)
        $id = $catalog["id"]
        if ($id -and $id -ne $name) {
            $skillIssues += @{ Severity = $SevError; Message = "catalog.yaml id '$id' does not match directory name '$name'" }
        }

        # scope_valid (error)
        $scope = $catalog["scope"]
        if (-not $scope) {
            $skillIssues += @{ Severity = $SevError; Message = "missing scope field" }
        } elseif ($scope -ne "general" -and $scope -ne "project") {
            $skillIssues += @{ Severity = $SevError; Message = "scope must be 'general' or 'project' (got '$scope')" }
        }

        # tags (warning)
        $tags = $catalog["tags"]
        if (-not $tags -or ($tags -is [string] -and $tags -eq "[]")) {
            $skillIssues += @{ Severity = $SevWarn; Message = "missing tags" }
        }

        # Extract description for length checks
        $content = Get-Content $skillMd -Raw
        $description = ""
        if ($content -match '(?ms)^---\s*\n(.*?)\n---') {
            $fm = $Matches[1]
            $fmLines = $fm -split "`n"
            for ($i = 0; $i -lt $fmLines.Count; $i++) {
                if ($fmLines[$i] -match '^description:\s*(.*)$') {
                    $val = $Matches[1].Trim()
                    if ($val -match '^[>|]-?\s*$') {
                        $parts = @()
                        for ($j = $i + 1; $j -lt $fmLines.Count; $j++) {
                            if ($fmLines[$j] -match '^\s+(.+)') { $parts += $Matches[1].Trim() } else { break }
                        }
                        $description = ($parts -join ' ').Trim()
                    } elseif ($val -match '^"(.+)"$') { $description = $Matches[1] }
                    else { $description = $val.Trim('"') }
                    break
                }
            }
        }
        # description_length (warning, lower + upper)
        if ($description.Length -lt 50) {
            $skillIssues += @{ Severity = $SevWarn; Message = "short description ($($description.Length) chars)" }
        } elseif ($description.Length -gt 500) {
            $skillIssues += @{ Severity = $SevWarn; Message = "long description ($($description.Length) chars, >500; Claude/Factory may truncate)" }
        }

        # targets_any (error) + single-target info
        $targets = $catalog["targets"]
        $activeTargets = @()
        if ($targets) {
            if ($targets["codex"]) { $activeTargets += "codex" }
            if ($targets["claude"]) { $activeTargets += "claude" }
            if ($targets["factory"]) { $activeTargets += "factory" }
            if ($targets["desktop"]) { $activeTargets += "desktop" }
        }
        if ($activeTargets.Count -eq 0) {
            $skillIssues += @{ Severity = $SevError; Message = "no targets enabled" }
        } elseif ($activeTargets.Count -eq 1 -and $scope -ne "project") {
            $skillIssues += @{ Severity = $SevInfo; Message = "single-target ($($activeTargets[0])) - consider cross-pollinating" }
        }

        # size_discipline_hard (error if >500 body lines)
        $bodyText = Get-SkillMdBody $skillMd
        $bodyLines = @($bodyText -split "`n").Count
        if ($bodyLines -gt 500) {
            $skillIssues += @{ Severity = $SevError; Message = "SKILL.md body is $bodyLines lines (>500); move detail to references/" }
        }

        # related_exists (error) + related_bidirectional (warning)
        $related = $catalog["related"]
        if ($related) {
            if ($related -isnot [array]) { $related = @($related) }
            foreach ($rid in $related) {
                if (-not $allSkills.ContainsKey($rid)) {
                    $skillIssues += @{ Severity = $SevError; Message = "related id '$rid' does not match any skill" }
                } else {
                    $otherCatalog = $allSkills[$rid]
                    $otherRelated = $otherCatalog["related"]
                    if ($otherRelated -and $otherRelated -isnot [array]) { $otherRelated = @($otherRelated) }
                    if (-not $otherRelated -or ($otherRelated -notcontains $name)) {
                        $skillIssues += @{ Severity = $SevWarn; Message = "'$rid' does not list '$name' in its related field" }
                    }
                }
            }
        }

        if ($skillIssues.Count -gt 0) {
            Write-Host "`n  $name" -ForegroundColor Yellow
            foreach ($issue in $skillIssues) {
                $sev = $issue.Severity
                $label = $sevLabels[$sev]
                $color = $sevColors[$sev]
                Write-Host "    - $label $($issue.Message)" -ForegroundColor $color
                if ($sev -eq $SevError) { $errorCount++ }
                elseif ($sev -eq $SevWarn) { $warnCount++ }
                else { $infoCount++ }
            }
        }
    }

    $total = $errorCount + $warnCount + $infoCount
    if ($total -eq 0) {
        Write-Host "`nNo issues found." -ForegroundColor Green
    } else {
        $summary = "$errorCount error(s), $warnCount warning(s), $infoCount info"
        if ($errorCount -gt 0) {
            Write-Host "`n$summary" -ForegroundColor Red
        } else {
            Write-Host "`n$summary" -ForegroundColor Yellow
        }
    }

    return $errorCount
}

