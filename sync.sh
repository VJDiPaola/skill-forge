# ── Status ───────────────────────────────────────────────────

show_status() {
    echo -e "\n${CYAN}=== Skill Library Status ===${NC}\n"
    printf "%-40s %-8s %-8s %-20s %-20s %-20s\n" "SKILL" "ORIGIN" "KIND" "CODEX" "CLAUDE" "FACTORY"
    printf "%-40s %-8s %-8s %-20s %-20s %-20s\n" "-----" "------" "----" "-----" "------" "-------"

    local total=0 ok=0 drift=0 missing=0

    for dir in "$LIBRARY_DIR"/*/; do
        [[ -d "$dir" ]] || continue
        local name=$(basename "$dir")
        local catalog_yaml="$dir/catalog.yaml"
        local origin=$(read_catalog_field "$catalog_yaml" "origin")
        local kind=$(read_catalog_field "$catalog_yaml" "kind")

        local codex_s="-" claude_s="-" factory_s="-"

        # Codex
        if [[ "$(read_catalog_target "$catalog_yaml" "codex")" == "true" ]]; then
            local dest="$CODEX_DIR/$name"
            if [[ -L "$dest" ]] || powershell.exe -NoProfile -Command "(Get-Item '$(cygpath -w "$dest")' -Force -ErrorAction SilentlyContinue).Attributes -band [System.IO.FileAttributes]::ReparsePoint" 2>/dev/null | grep -qi "true"; then
                codex_s="OK (junction)"
                ok=$((ok + 1))
            elif [[ -d "$dest" ]]; then
                codex_s="DRIFT (not junction)"
                drift=$((drift + 1))
            else
                codex_s="MISSING"
                missing=$((missing + 1))
            fi
        fi

        # Claude
        if [[ "$(read_catalog_target "$catalog_yaml" "claude")" == "true" ]]; then
            local dest="$CLAUDE_DIR/$name.md"
            if [[ -f "$dest" ]]; then
                if is_autogenerated "$dest"; then
                    claude_s="OK (generated)"
                    ok=$((ok + 1))
                else
                    claude_s="DRIFT (edited)"
                    drift=$((drift + 1))
                fi
            else
                claude_s="MISSING"
                missing=$((missing + 1))
            fi
        fi

        # Factory
        if [[ "$(read_catalog_target "$catalog_yaml" "factory")" == "true" ]]; then
            local dest="$FACTORY_DIR/$name.md"
            if [[ -f "$dest" ]]; then
                if is_autogenerated "$dest"; then
                    factory_s="OK (generated)"
                    ok=$((ok + 1))
                else
                    factory_s="DRIFT (edited)"
                    drift=$((drift + 1))
                fi
            else
                factory_s="MISSING"
                missing=$((missing + 1))
            fi
        fi

        printf "%-40s %-8s %-8s %-20s %-20s %-20s\n" "$name" "$origin" "$kind" "$codex_s" "$claude_s" "$factory_s"
        total=$((total + 1))
    done

    echo ""
    echo -e "${CYAN}Total: $total skills | Synced: $ok | Drift: $drift | Missing: $missing${NC}"
}

# ── Search ─────────────────────────────────────────────────

search_skills() {
    local query="$1"
    if [[ -z "$query" ]]; then
        echo "Usage: $0 search <query>"
        return
    fi
    local found=0
    for dir in "$LIBRARY_DIR"/*/; do
        [[ -d "$dir" ]] || continue
        local name=$(basename "$dir")
        local skill_md="$dir/SKILL.md"
        local catalog_yaml="$dir/catalog.yaml"
        [[ -f "$skill_md" ]] || continue

        local tags=$(read_catalog_field "$catalog_yaml" "tags")
        local scope=$(read_catalog_field "$catalog_yaml" "scope")
        local codex_t=$(read_catalog_target "$catalog_yaml" "codex")
        local claude_t=$(read_catalog_target "$catalog_yaml" "claude")
        local factory_t=$(read_catalog_target "$catalog_yaml" "factory")
        local targets=""
        [[ "$codex_t" == "true" ]] && targets+="codex "
        [[ "$claude_t" == "true" ]] && targets+="claude "
        [[ "$factory_t" == "true" ]] && targets+="factory "

        # Extract description
        local in_fm=$(awk 'BEGIN{p=0} /^---$/{p++; next} p==1{print} p>=2{exit}' "$skill_md")
        local desc_line=$(echo "$in_fm" | grep -n '^description:' | head -1)
        local desc=""
        if [[ -n "$desc_line" ]]; then
            local desc_num=${desc_line%%:*}
            local desc_val=$(echo "$desc_line" | sed 's/^[0-9]*:description:\s*//')
            if echo "$desc_val" | grep -qE '^[>|]-?\s*$'; then
                desc=$(echo "$in_fm" | tail -n +$((desc_num + 1)) | awk '/^[[:space:]]+/{gsub(/^[[:space:]]+/,""); printf "%s ", $0; next} {exit}' | sed 's/ $//')
            else
                desc=$(echo "$desc_val" | tr -d '"')
            fi
        fi

        local searchable="$name $desc $tags"
        if echo "$searchable" | grep -qi "$query"; then
            echo -e "  ${GREEN}$name${NC} ${GRAY}[$targets]${NC}"
            echo -e "    ${GRAY}${desc:0:100}${NC}"
            [[ -n "$tags" ]] && echo -e "    ${CYAN}tags: $tags${NC}"
            [[ "$scope" == "project" ]] && echo -e "    ${YELLOW}scope: project${NC}"
            found=$((found + 1))
        fi
    done
    echo -e "\n${CYAN}$found skill(s) matched '$query'${NC}"
}

# ── Main ───────────────────────────────────────────────────

COMMAND="${1:-}"
TARGET="${2:-all}"

if [[ -z "$COMMAND" ]]; then
    echo "Usage: $0 {push|pull|status} [codex|claude|factory|all]"
    exit 1
fi

echo -e "${CYAN}Skill Library Sync${NC}"
echo -e "${GRAY}Library: $LIBRARY_DIR${NC}"

case "$COMMAND" in
    push)
        [[ "$TARGET" == "all" || "$TARGET" == "codex" ]]   && push_codex
        [[ "$TARGET" == "all" || "$TARGET" == "claude" ]]   && push_claude
        [[ "$TARGET" == "all" || "$TARGET" == "factory" ]]  && push_factory
        [[ "$TARGET" == "all" || "$TARGET" == "desktop" ]]  && push_desktop
        update_catalog_json
        echo -e "\n${GREEN}Push complete.${NC}"
        ;;
    pull)
        [[ "$TARGET" == "all" || "$TARGET" == "codex" ]]   && pull_codex
        [[ "$TARGET" == "all" || "$TARGET" == "claude" ]]   && pull_claude
        [[ "$TARGET" == "all" || "$TARGET" == "factory" ]]  && pull_factory
        update_catalog_json
        echo -e "\n${GREEN}Pull complete.${NC}"
        ;;
    status)
        show_status
        ;;
    diff)
        [[ "$TARGET" == "all" || "$TARGET" == "codex" ]]   && diff_codex
        [[ "$TARGET" == "all" || "$TARGET" == "claude" ]]   && diff_claude
        [[ "$TARGET" == "all" || "$TARGET" == "factory" ]]  && diff_factory
        [[ "$TARGET" == "all" || "$TARGET" == "desktop" ]]  && diff_desktop
        ;;
    search)
        search_skills "$TARGET"
        ;;
    *)
        echo "Unknown command: $COMMAND"
        echo "Usage: $0 {push|pull|status|diff|search} [codex|claude|factory|all|<query>]"
        exit 1
        ;;
esac
